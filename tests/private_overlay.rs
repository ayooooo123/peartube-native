    /// The receiving end of a fake connection. A big frame is handed on as its own allocation,
    /// counted in [`FakeNet::big_frames_alive`] until the last view into it is dropped.
    struct TrackingReader {
        inner: protomux::memory::MemoryReader,
        big_frames: Arc<AtomicUsize>,
    }

    struct TrackedFrame {
        data: Vec<u8>,
        alive: Arc<AtomicUsize>,
    }

    impl AsRef<[u8]> for TrackedFrame {
        fn as_ref(&self) -> &[u8] {
            &self.data
        }
    }

    impl Drop for TrackedFrame {
        fn drop(&mut self) {
            self.alive.fetch_sub(1, Ordering::SeqCst);
        }
    }

    impl protomux::FrameRead for TrackingReader {
        async fn read(&mut self) -> io::Result<Option<Bytes>> {
            let frame = protomux::FrameRead::read(&mut self.inner).await?;
            Ok(frame.map(|frame| {
                if frame.len() < BIG_FRAME {
                    return frame;
                }
                self.big_frames.fetch_add(1, Ordering::SeqCst);
                Bytes::from_owner(TrackedFrame {
                    data: frame.to_vec(),
                    alive: Arc::clone(&self.big_frames),
                })
            }))
        }
    }

    impl FakeConn {
        fn mark_closed(&self) {
            self.closed.send_replace(true);
        }
    }

    impl Connection for FakeConn {
        fn as_any(&self) -> &dyn std::any::Any {
            self
        }

        fn remote_public_key(&self) -> [u8; 32] {
            self.remote_public_key
        }

        fn remote_host(&self) -> Option<IpAddr> {
            Some(self.peer.addr.ip())
        }

        fn remote_port(&self) -> Option<u16> {
            Some(self.peer.addr.port())
        }

        fn is_closed(&self) -> bool {
            *self.closed.borrow()
        }

        fn closed(&self) -> BoxFuture<'static, ()> {
            let mut rx = self.closed.subscribe();
            Box::pin(async move {
                let _ = rx.wait_for(|closed| *closed).await;
            })
        }

        fn destroy(&self) {
            self.mark_closed();
            self.duplex.lock().unwrap_or_else(|e| e.into_inner()).take();
        }
    }

