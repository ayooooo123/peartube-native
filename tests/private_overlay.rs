static GUARD_SPEC: Spec = Spec {
    protocol: &GUARD,
    label: "Guard",
    refused: "refused",
    duplicate: "duplicate",
    timed_out: "timed out",
};
const WAIT: Duration = Duration::from_secs(5);

/// A peer's own connection to a guard, with its mux.
struct Client {
    node: fake::FakeDht,
    conn: Arc<dyn Connection>,
    mux: Mux,
}

async fn dial(net: &Arc<FakeNet>, guard: [u8; 32], seed: u8) -> Client {
    let node = net.node();
    let conn = node.connect(guard, &key(seed)).await.expect("connect");
    let mux = node.protomux(&conn).await.expect("mux");
    mux.ready();
    Client { node, conn, mux }
}

async fn channel(mux: &Mux) -> Control {
    open_channel(mux, &GUARD_SPEC, ControlHandlers::default(), WAIT)
        .await
        .expect("guard channel")
}

async fn ask(control: &Control, op: u64, body: impl Into<Body>) -> Body {
    control.call(op, body.into(), WAIT).await.expect("answer")
}

async fn hello(control: &Control, role: &str) -> Body {
    ask(control, op::HELLO, GuardHello { role: role.into() }).await
}

fn ack(status: u64) -> Body {
    GuardAck { status }.into()
}

fn not_ready() -> Body {
    GuardReady {
        status: 0,
        udx_id: 0,
    }
    .into()
}

fn register(token: [u8; 32]) -> GuardRegister {
    GuardRegister {
        route_token: token,
        ttl_ms: ROUTE_TTL_MS,
    }
}

fn rv_register(topic: [u8; 32], slot_id: [u8; 16], sealed_card: &[u8]) -> GuardRvRegister {
    GuardRvRegister {
        topic,
        slot_id,
        ttl_ms: ROUTE_TTL_MS,
        sealed_card: sealed_card.to_vec().into(),
    }
}

/// A live route on `guard`, published the way the app's diagnostics page does: a standalone
/// endpoint registers a token, answers `incOpen`, and puts its sealed card in the DHT. Returns
/// the token, read back from the card as `attemptDirectHopBypass` reads it.
async fn live_route(
    net: &Arc<FakeNet>,
    guard: [u8; 32],
    seed: u8,
) -> (StandaloneRouteCard, [u8; 32]) {
    let publisher = net.node();
    let advertised = key(seed);
    let card = publish_standalone_route_card(
        publisher.as_dht(),
        StandaloneCardOptions {
            host: None,
            bootstrap: Vec::new(),
            guard_public_key: guard,
            advertised_key_pair: advertised.clone(),
            responder_key_pair: None,
            on_inner_connection: None,
        },
    )
    .await
    .expect("route card");
    let record = publisher
        .mutable_get(advertised.public_key)
        .await
        .expect("mutable get")
        .expect("published card");
    let plain = open_box(&record.value, &peer_seal_key(&advertised.public_key)).expect("seal");
    let decoded = decode_and_verify_card(&plain, now_ms(), Some(&advertised.public_key))
        .expect("signed card");
    assert_eq!(decoded.guard_public_key, guard);
    (card, decoded.route_token)
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn guard_counts_roles_and_limits() {
    let net = FakeNet::new();
    let guard = create_private_guard(net.node().as_dht(), guard_options(7))
        .await
        .expect("guard");
    let client = dial(&net, guard.public_key(), 8).await;
    let rpc = channel(&client.mux).await;

    // The guard is found under the v2 topics only.
    for i in 0..4 {
        let v1 = peartube_native::private_overlay::hash(
            format!("peartube/private-guard/v1/{i}").as_bytes(),
        );
        assert!(client.node.lookup(v1).await.unwrap().is_empty());
        assert!(
            client
                .node
                .lookup(GUARD_TOPICS[i])
                .await
                .unwrap()
                .contains(&guard.public_key())
        );
    }

    // A request that needs a role, sent before `hello`, is refused.
    assert_eq!(ask(&rpc, op::REGISTER, register([0x55; 32])).await, ack(0));
    assert_eq!(guard.stats().registered_routes, 0);
    // An unknown role is refused without cutting the connection off.
    assert_eq!(hello(&rpc, "relay").await, ack(0));
    assert!(!client.conn.is_closed());

    assert_eq!(hello(&rpc, "endpoint").await, ack(1));
    assert_eq!(ask(&rpc, op::REGISTER, register([0x55; 32])).await, ack(1));
    assert_eq!(guard.stats().registered_routes, 1);
    // A ttl above 2^32-1 is out of bounds.
    let long = GuardRegister {
        route_token: [0x56; 32],
        ttl_ms: 1 << 32,
    };
    assert_eq!(ask(&rpc, op::REGISTER, long).await, ack(0));

    // A route card write is forwarded with the endpoint's own signature.
    let endpoint_key = key(9);
    let card = encode_signed_card(
        &endpoint_key,
        &guard.public_key(),
        &[0x66u8; 32],
        1,
        now_ms() + ROUTE_TTL_MS,
    );
    let sealed = seal_box(&card, &peer_seal_key(&endpoint_key.public_key));
    let put = GuardPutMutable {
        public_key: endpoint_key.public_key,
        seq: 1,
        signature: sign_dht_mutable(1, &sealed, &endpoint_key),
        value: sealed.clone().into(),
    };
    assert_eq!(ask(&rpc, op::PUT_MUTABLE, put.clone()).await, ack(1));
    assert_eq!(guard.stats().put_mutable_count, 1);

    // The same write can be made to fail, exercising the endpoint's retry path.
    guard.fail_next_mutable_put(1);
    assert_eq!(ask(&rpc, op::PUT_MUTABLE, put.clone()).await, ack(0));
    // Values of 0 or more than 512 bytes are refused before the DHT, even signed for their own
    // bytes; 512 bytes pass.
    let other = key(10);
    let signed = |value: Vec<u8>| GuardPutMutable {
        public_key: other.public_key,
        seq: 1,
        signature: sign_dht_mutable(1, &value, &other),
        value: value.into(),
    };
    let reached = net.mutable_puts();
    for value in [Vec::new(), vec![7; 513]] {
        assert_eq!(ask(&rpc, op::PUT_MUTABLE, signed(value)).await, ack(0));
    }
    assert_eq!(
        net.mutable_puts(),
        reached,
        "a refused value reached the DHT"
    );
    assert_eq!(guard.stats().put_mutable_count, 1);
    assert_eq!(
        ask(&rpc, op::PUT_MUTABLE, signed(vec![7; 512])).await,
        ack(1)
    );
    assert_eq!(net.mutable_puts(), reached + 1);
    assert_eq!(guard.stats().put_mutable_count, 2);

    // The record reads back; "not found" is an absent record.
    let Body::GuardGetResult(found) = ask(
        &rpc,
        op::GET_MUTABLE,
        GuardKey {
            key: endpoint_key.public_key,
        },
    )
    .await
    else {
        panic!("not a get result")
    };
    let record = found.record.expect("record");
    assert_eq!((record.seq, &record.value[..]), (1, &sealed[..]));
    assert_eq!(
        ask(&rpc, op::GET_MUTABLE, GuardKey { key: [0x99; 32] }).await,
        GuardGetResult { record: None }.into()
    );

    // A rendezvous slot registers; an endpoint may not fetch it as a hop.
    assert_eq!(
        ask(
            &rpc,
            op::RV_REGISTER,
            rv_register([0x77; 32], [0x88; 16], &sealed)
        )
        .await,
        ack(1)
    );
    assert_eq!(guard.stats().rendezvous_topics, 1);
    assert_eq!(guard.stats().rv_register_count, 1);
    assert_eq!(
        ask(&rpc, op::RV_FETCH, GuardKey { key: [0x77; 32] }).await,
        GuardCards { cards: Vec::new() }.into()
    );
    // The endpoint's own lookup sees it.
    assert_eq!(
        ask(&rpc, op::RV_LOOKUP, GuardKey { key: [0x77; 32] }).await,
        GuardCards {
            cards: vec![sealed.clone().into()]
        }
        .into()
    );

    client.conn.destroy();
    eventually("session cleanup", Duration::from_secs(5), || {
        guard.stats().registered_routes == 0 && guard.stats().rendezvous_topics == 0
    })
    .await;
    guard.close().await.expect("guard close");
}

/// The released order of `putMutable`'s checks: an empty value is refused without spending a
/// DHT budget slot, a value over 512 bytes spends one and is then refused. Told apart by where
/// the connection's budget runs out.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn only_an_oversized_put_spends_the_dht_budget() {
    let net = FakeNet::new();
    let guard = create_private_guard(net.node().as_dht(), guard_options(36))
        .await
        .expect("guard");
    let client = dial(&net, guard.public_key(), 37).await;
    let rpc = channel(&client.mux).await;
    assert_eq!(hello(&rpc, "endpoint").await, ack(1));
    let writer = key(35);
    let signed = |value: Vec<u8>| GuardPutMutable {
        public_key: writer.public_key,
        seq: 1,
        signature: sign_dht_mutable(1, &value, &writer),
        value: value.into(),
    };
    assert_eq!(
        ask(&rpc, op::PUT_MUTABLE, signed(vec![1; 10])).await,
        ack(1)
    );
    for _ in 0..10 {
        assert_eq!(ask(&rpc, op::PUT_MUTABLE, signed(Vec::new())).await, ack(0));
    }
    assert_eq!(
        ask(&rpc, op::PUT_MUTABLE, signed(vec![1; 513])).await,
        ack(0)
    );
    // Two slots spent: the remaining reads find the record, the next one is over budget.
    let read = GuardKey {
        key: writer.public_key,
    };
    let found = |answer: Body| {
        matches!(
            answer,
            Body::GuardGetResult(GuardGetResult { record: Some(_) })
        )
    };
    for i in 2..peartube_native::private_overlay::MAX_DHT_OPS_PER_10S {
        assert!(
            found(ask(&rpc, op::GET_MUTABLE, read.clone()).await),
            "read {i} refused: an empty value spent the budget"
        );
    }
    assert!(
        !found(ask(&rpc, op::GET_MUTABLE, read).await),
        "the oversized value did not spend the budget"
    );
}

/// Role separation, first half: a session that said hello as `endpoint` and then asks for
/// `hopOpen` on a live route is refused. Fails if the guard splices it (status 1).
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn an_endpoint_session_cannot_open_a_hop() {
    let net = FakeNet::new();
    let guard = create_private_guard(net.node().as_dht(), guard_options(41))
        .await
        .expect("guard");
    let (_route, token) = live_route(&net, guard.public_key(), 42).await;
    let attacker = dial(&net, guard.public_key(), 43).await;
    let rpc = channel(&attacker.mux).await;
    assert_eq!(hello(&rpc, "endpoint").await, ack(1));
    let raw = attacker
        .node
        .create_raw_stream(true, Arc::new(|_, _| true))
        .await
        .expect("raw stream");
    let open = GuardOpen {
        route_token: token,
        udx_id: u64::from(raw.id()),
    };
    assert_eq!(ask(&rpc, op::HOP_OPEN, open).await, not_ready());
    assert_eq!(guard.stats().active_circuits, 0);
    // Refused, not cut off: only a failed hop claim destroys a connection.
    assert!(!attacker.conn.is_closed());
    assert_eq!(hello(&rpc, "endpoint").await, ack(1));
    // The same route opens for a session that is a hop: the refusal above is the role's.
    let (hop, hop_rpc) = hop_session(&net, guard.public_key(), 40).await;
    let hop_raw = raw_stream(&hop).await;
    let open = GuardOpen {
        route_token: token,
        udx_id: u64::from(hop_raw.id()),
    };
    let Body::GuardReady(ready) = ask(&hop_rpc, op::HOP_OPEN, open).await else {
        panic!("not a ready")
    };
    assert_eq!(ready.status, 1, "an authorized hop is spliced");
}

/// What `on_control_peer` hears, as (role, key).
type Admitted = Arc<Mutex<Vec<(&'static str, [u8; 32])>>>;

fn recording(seed: u8, allow_loopback: bool, admitted: &Admitted) -> GuardOptions {
    let admitted = Arc::clone(admitted);
    GuardOptions {
        allow_loopback: Some(allow_loopback),
        on_control_peer: Some(Arc::new(move |peer: ControlPeer| {
            admitted
                .lock()
                .unwrap()
                .push((peer.role.as_str(), peer.remote_public_key))
        })),
        ..guard_options(seed)
    }
}

/// Role separation, second half: a key that is not an advertised guard and claims `hop` gets no
/// hop rights, and its connection is destroyed. Fails if `hello` is granted or `hopOpen` splices.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn an_unadvertised_hop_claim_is_cut_off() {
    let net = FakeNet::new();
    let admitted: Admitted = Arc::default();
    let guard = create_private_guard(net.node().as_dht(), recording(44, true, &admitted))
        .await
        .expect("guard");
    let (_route, token) = live_route(&net, guard.public_key(), 45).await;
    let attacker = dial(&net, guard.public_key(), 46).await;
    let rpc = channel(&attacker.mux).await;
    let claim = rpc
        .call(op::HELLO, GuardHello { role: "hop".into() }.into(), WAIT)
        .await;
    assert!(
        !matches!(claim, Ok(Body::GuardAck(GuardAck { status: 1 }))),
        "an unadvertised key was granted the hop role"
    );
    tokio::time::timeout(WAIT, attacker.conn.closed())
        .await
        .expect("the guard destroys the connection");
    let raw = attacker
        .node
        .create_raw_stream(true, Arc::new(|_, _| true))
        .await
        .expect("raw stream");
    let open = GuardOpen {
        route_token: token,
        udx_id: u64::from(raw.id()),
    };
    let reply = rpc.call(op::HOP_OPEN, open.into(), WAIT).await;
    assert!(
        !matches!(reply, Ok(Body::GuardReady(GuardReady { status: 1, .. }))),
        "the spoofed hop was spliced"
    );
    assert_eq!(guard.stats().active_circuits, 0);
    assert!(
        admitted
            .lock()
            .unwrap()
            .iter()
            .all(|(role, _)| *role != "hop"),
        "a hop was admitted"
    );

    // An advertised guard key in no eligible bucket (loopback, not allowed here) is cut off too.
    let strict_admitted: Admitted = Arc::default();
    let strict = create_private_guard(net.node().as_dht(), recording(39, false, &strict_admitted))
        .await
        .expect("strict guard");
    let claimant = dial(&net, strict.public_key(), 38).await;
    for topic in GUARD_TOPICS.iter() {
        claimant.node.announce(*topic, &key(38)).await.unwrap();
    }
    let rpc = channel(&claimant.mux).await;
    let claim = rpc
        .call(op::HELLO, GuardHello { role: "hop".into() }.into(), WAIT)
        .await;
    assert!(!matches!(claim, Ok(Body::GuardAck(GuardAck { status: 1 }))));
    tokio::time::timeout(WAIT, claimant.conn.closed())
        .await
        .expect("the guard destroys the connection");
    assert!(strict_admitted.lock().unwrap().is_empty());
}

async fn next_frame(raw: &mut protomux::Channel) -> Frame {
    loop {
        match tokio::time::timeout(WAIT, raw.recv())
            .await
            .expect("a frame")
        {
            Some(Event::Message(message)) => {
                assert_eq!(message.kind, 0);
                return compact_encoding::decode(message.data).expect("frame");
            }
            Some(Event::Opened { .. }) => continue,
            other => panic!("channel ended: {other:?}"),
        }
    }
}

fn frame(kind: u64, op: u64, id: u64, value: Bytes) -> Frame {
    Frame {
        kind,
        op,
        id,
        value,
    }
}

/// A valid `hello` as `endpoint`, answered with an accepting ack.
async fn healthy(raw: &mut protomux::Channel, id: u64) {
    let hello = compact_encoding::encode(&GuardHello {
        role: "endpoint".into(),
    });
    raw.sender().send(0, &frame(0, op::HELLO, id, hello));
    let ok = compact_encoding::encode(&GuardAck { status: 1 });
    assert_eq!(next_frame(raw).await, frame(1, op::HELLO, id, ok));
}

/// The hostile cases of contract section 8 against the real serving guard: each is dropped or
/// answered with the envelope's error, the process and connection stay, valid requests keep
/// working, the eighth bad value closes only this channel, and a `/v1` peer sees no frame.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn hostile_frames_leave_the_guard_serving() {
    let net = FakeNet::new();
    let guard = create_private_guard(net.node().as_dht(), guard_options(47))
        .await
        .expect("guard");
    let client = dial(&net, guard.public_key(), 48).await;
    let mut raw = client
        .mux
        .open_channel(ChannelOptions::new(GUARD.name))
        .expect("raw channel");
    assert!(matches!(
        tokio::time::timeout(WAIT, raw.recv()).await.unwrap(),
        Some(Event::Opened { .. })
    ));
    healthy(&mut raw, 1).await;

    // Bytes after the last known field, in a value and in a frame, are ignored.
    let mut value = compact_encoding::encode(&GuardHello {
        role: "endpoint".into(),
    })
    .to_vec();
    value.push(0);
    let mut bytes = compact_encoding::encode(&frame(0, op::HELLO, 2, value.into())).to_vec();
    bytes.push(0);
    raw.sender().send_raw(0, &bytes);
    assert_eq!(
        next_frame(&mut raw).await,
        frame(
            1,
            op::HELLO,
            2,
            compact_encoding::encode(&GuardAck { status: 1 })
        )
    );

    // Dropped without an answer; the first six count as bad.
    let big = (1u64 << 53) + 1;
    let dropped = [
        Bytes::from(vec![0u8; 65_537]),
        compact_encoding::encode(&frame(0, 0, big, Bytes::new())),
        compact_encoding::encode(&frame(0, big, 3, Bytes::new())),
        compact_encoding::encode(&frame(big, 0, 3, Bytes::new())),
        compact_encoding::encode(&frame(4, 0, 3, Bytes::new())),
        compact_encoding::encode(&frame(0, op::HELLO, 0, value_of_hello())),
        compact_encoding::encode(&frame(3, op::RV_UNREGISTER, 9, Bytes::new())),
        compact_encoding::encode(&frame(
            1,
            op::HELLO,
            77,
            compact_encoding::encode(&GuardAck { status: 1 }),
        )),
    ];
    for (i, bytes) in dropped.into_iter().enumerate() {
        raw.sender().send_raw(0, &bytes);
        healthy(&mut raw, 100 + i as u64).await;
    }
    // Answered at once with the envelope's code, as (kind, op, id).
    for (op_index, value, code) in [
        (99, Bytes::new(), "UNKNOWN_OP"),
        (op::CIRCUIT_DEAD, Bytes::new(), "UNKNOWN_OP"),
        (op::INC_OPEN, Bytes::new(), "UNKNOWN_OP"),
        (op::REGISTER, Bytes::new(), "DECODE_ERROR"),
    ] {
        raw.sender().send(0, &frame(0, op_index, 3, value));
        let reply = tokio::time::timeout(Duration::from_secs(1), next_frame(&mut raw))
            .await
            .expect("an immediate error");
        assert_eq!((reply.kind, reply.op, reply.id), (2, op_index, 3));
        let error: RemoteError = compact_encoding::decode(reply.value).unwrap();
        assert_eq!(error.code, code);
        healthy(&mut raw, 7).await;
    }
    assert!(!client.conn.is_closed());
    // Seven strikes so far; the eighth, a `udxId` above 2^53-1, is answered and then closes
    // this channel.
    let unsafe_open = {
        let mut bytes = compact_encoding::encode(&GuardOpen {
            route_token: [1; 32],
            udx_id: 1,
        })
        .to_vec();
        bytes.truncate(32);
        bytes.extend_from_slice(&[0xff; 9]);
        Bytes::from(bytes)
    };
    raw.sender()
        .send(0, &frame(0, op::HOP_OPEN, 4, unsafe_open));
    let reply = next_frame(&mut raw).await;
    assert_eq!((reply.kind, reply.op, reply.id), (2, op::HOP_OPEN, 4));
    assert!(matches!(
        tokio::time::timeout(WAIT, raw.recv()).await.unwrap(),
        Some(Event::Closed { .. })
    ));
    // The connection stays, a new channel on it is served, and so is another client.
    assert!(!client.conn.is_closed() && !client.mux.is_destroyed());
    let again = channel(&client.mux).await;
    assert_eq!(hello(&again, "endpoint").await, ack(1));
    let other = dial(&net, guard.public_key(), 49).await;
    assert_eq!(hello(&channel(&other.mux).await, "endpoint").await, ack(1));

    // A peer that only offers the old name is refused and sees no frame.
    let mut old = client
        .mux
        .open_channel(ChannelOptions::new("peartube/private-guard/v1"))
        .expect("old channel");
    assert!(matches!(
        tokio::time::timeout(WAIT, old.recv()).await.unwrap(),
        Some(Event::Closed { .. }) | None
    ));
    assert!(!client.conn.is_closed());
    guard.close().await.expect("guard close");
}

