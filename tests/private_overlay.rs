#[test]
fn route_cards_are_byte_identical_and_verifiable() {
    let fixtures = json();
    let cards = &fixtures["cards"];
    let key_pair = KeyPair::from_seed(hex32(cards["seed"].as_str().unwrap()));
    let guard = hex32(cards["guardPublicKeyHex"].as_str().unwrap());
    let token = hex32(cards["routeTokenHex"].as_str().unwrap());
    let seq = cards["seq"].as_u64().unwrap();
    let expires_at = cards["expiresAt"].as_u64().unwrap();
    let card_bytes = encode_signed_card(&key_pair, &guard, &token, seq, expires_at);
    assert_eq!(to_hex(&card_bytes), cards["cardHex"].as_str().unwrap());

    // Every verdict comes from the app's own `decodeAndVerifyCard`.
    for entry in cards["cases"].as_array().unwrap() {
        let now = entry["now"].as_u64().unwrap();
        let expected_key = entry["expectedKeyHex"].as_str().map(hex32);
        let decoded = decode_and_verify_card(&card_bytes, now, expected_key.as_ref());
        assert_eq!(
            decoded.is_some(),
            entry["verified"].as_bool().unwrap(),
            "{}: verdicts differ",
            entry["label"].as_str().unwrap()
        );
        if let Some(decoded) = decoded {
            assert_eq!(decoded.guard_public_key, guard);
            assert_eq!(decoded.route_token, token);
            assert_eq!(decoded.seq, seq);
            assert_eq!(decoded.expires_at, expires_at);
        }
    }

    let mut tampered = card_bytes.clone();
    tampered[112] ^= 1;
    assert!(decode_and_verify_card(&tampered, cards["now"].as_u64().unwrap(), None).is_none());
}

#[test]
fn sealed_cards_open_with_the_app_nonce_layout() {
    let fixtures = json();
    let sealed = &fixtures["sealedBox"];
    let seal_key = hex32(sealed["sealKeyHex"].as_str().unwrap());
    let sealed_bytes = unhex(sealed["sealedHex"].as_str().unwrap());
    assert_eq!(
        open_box(&sealed_bytes, &seal_key).expect("open app sealed box"),
        unhex(sealed["plainHex"].as_str().unwrap())
    );
    // Our sealing must use the same nonce||secretbox layout.
    let ours = seal_box(b"another card", &seal_key);
    assert_eq!(
        open_box(&ours, &seal_key).as_deref(),
        Some(&b"another card"[..])
    );
    assert_eq!(ours.len(), 24 + 16 + 12);
    assert!(open_box(&ours, &[0u8; 32]).is_none());
}

#[test]
fn mutable_signatures_match_the_app() {
    let fixtures = json();
    let mutable = &fixtures["mutable"];
    let key_pair = KeyPair::from_seed(hex32(mutable["seed"].as_str().unwrap()));
    let value = unhex(mutable["valueHex"].as_str().unwrap());
    let seq = mutable["seq"].as_u64().unwrap();
    let signature = sign_dht_mutable(seq, &value, &key_pair);
    assert_eq!(
        to_hex(&signature),
        mutable["signatureHex"].as_str().unwrap()
    );
    assert!(verify_dht_mutable(
        &signature,
        seq,
        &value,
        &key_pair.public_key
    ));
    assert!(!verify_dht_mutable(
        &signature,
        seq + 1,
        &value,
        &key_pair.public_key
    ));
    assert!(!verify_dht_mutable(
        &unhex(mutable["tamperedSignatureHex"].as_str().unwrap()),
        seq,
        &value,
        &key_pair.public_key
    ));
    // `NS_MUTABLE_PUT` is `namespace('hyperswarm/dht', [4,5,6,0,1,10])[2]`.
    assert_eq!(
        *NS_MUTABLE_PUT,
        peeroxide_dht::crypto::namespace("hyperswarm/dht", &[4, 5, 6, 0, 1, 10])[2]
    );
    assert_ne!(*NS_MUTABLE_PUT, [0u8; 32]);
    assert!(is_local_bootstrap(Some("127.0.0.1"), &[]));
    assert!(is_local_bootstrap(None, &["127.0.0.1:49737".to_owned()]));
    assert!(!is_local_bootstrap(
        Some("10.0.0.1"),
        &["1.2.3.4:1".to_owned()]
    ));
}

