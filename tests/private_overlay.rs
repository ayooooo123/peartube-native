/// Two scripted guards on the network, in the given order of seeds.
async fn two_scripted_guards(
    net: &Arc<FakeNet>,
    seeds: [u8; 2],
    hold_puts: bool,
) -> (Arc<Script>, Arc<Script>, Vec<Arc<dyn Server>>) {
    let scripts = [Arc::new(Script::default()), Arc::new(Script::default())];
    let mut servers = Vec::new();
    for (script, seed) in scripts.iter().zip(seeds) {
        script.hold_puts.store(hold_puts, Ordering::SeqCst);
        servers.push(fake_guard(net, seed, scripted(Arc::clone(script))).await.2);
    }
    let [a, b] = scripts;
    (a, b, servers)
}

/// (primary, secondary): the primary is the one the route was registered on.
fn primary_first(a: Arc<Script>, b: Arc<Script>) -> (Arc<Script>, Arc<Script>) {
    if a.token.lock().unwrap().is_some() {
        (a, b)
    } else {
        (b, a)
    }
}

/// Contract section 7 with two guards: when one of two usable guards goes, the client is not
/// READY, also when a publish under way finishes after the loss, and sends no `dialOpen`, also
/// for a dial already under way, across full retry cycles. A second usable guard makes it READY
/// again.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn losing_one_of_two_guards_stops_ready_and_every_dial() {
    let net = FakeNet::new();
    let (a, b, _servers) = two_scripted_guards(&net, [90, 91], true).await;
    let swarm = endpoint_swarm(&net, 92);
    let routing = swarm.private_routing();

    // A publish holds on the primary's putMutable reply while the secondary's channel closes.
    eventually("a held publish", WAIT, || {
        a.puts_waiting.load(Ordering::SeqCst) + b.puts_waiting.load(Ordering::SeqCst) == 1
    })
    .await;
    let (primary, secondary) = primary_first(a, b);
    secondary.refuse.store(true, Ordering::SeqCst);
    net.lookups.hold();
    secondary.latest().close();
    eventually("one usable guard", WAIT, || {
        routing.exposure_report().guards == 1
    })
    .await;
    primary.hold_puts.store(false, Ordering::SeqCst);
    eventually("the publish answered", WAIT, || {
        primary.puts_waiting.load(Ordering::SeqCst) == 0
    })
    .await;
    for _ in 0..50 {
        assert_ne!(routing.status(), RoutingState::Ready, "READY on one guard");
        tokio::time::sleep(Duration::from_millis(10)).await;
    }

    // A second usable guard: READY again.
    secondary.refuse.store(false, Ordering::SeqCst);
    net.lookups.release();
    eventually("ready on two guards", Duration::from_secs(15), || {
        routing.status() == RoutingState::Ready && routing.exposure_report().guards == 2
    })
    .await;

    // A dial under way (held at its raw stream) when the secondary goes sends no dialOpen.
    let destination = key(93);
    let far_guard = key(94).public_key;
    *primary.record.lock().unwrap() = Some(record_of(&destination, far_guard, [0x93; 32]));
    net.raws.hold();
    swarm.join_peer(destination.public_key);
    eventually("a dial under way", WAIT, || net.raws.waiting() == 1).await;
    secondary.refuse.store(true, Ordering::SeqCst);
    secondary.latest().close();
    eventually("one usable guard", WAIT, || {
        routing.exposure_report().guards == 1
    })
    .await;
    net.raws.release();
    // Two more refused rediscoveries are two full retry cycles.
    let hellos = secondary.hellos.load(Ordering::SeqCst);
    eventually("two retry cycles", Duration::from_secs(15), || {
        secondary.hellos.load(Ordering::SeqCst) >= hellos + 2
    })
    .await;
    assert!(
        primary.dial_opens.lock().unwrap().is_empty(),
        "a dialOpen went out with one usable guard"
    );
    assert!(!net.dials().contains(&destination.public_key));
    assert!(!net.dials().contains(&far_guard));
    assert_ne!(routing.status(), RoutingState::Ready);
    assert_eq!(routing.exposure_report().guards, 1);
    swarm.destroy().await;
}

