/// A guard announced on the v2 topics whose connections are served by `serve` (given the
/// guard's own node, for raw streams); returns the guard key and every connection it accepted.
async fn fake_guard(
    net: &Arc<FakeNet>,
    seed: u8,
    serve: impl Fn(fake::FakeDht, Mux, Arc<dyn Connection>) + Send + Sync + 'static,
) -> (
    [u8; 32],
    Arc<Mutex<Vec<Arc<dyn Connection>>>>,
    Arc<dyn Server>,
) {
    let node = net.node();
    let accepted: Arc<Mutex<Vec<Arc<dyn Connection>>>> = Arc::default();
    let serve = Arc::new(serve);
    let handler: ConnectionHandler = {
        let node = node.clone();
        let accepted = Arc::clone(&accepted);
        Arc::new(move |conn: Arc<dyn Connection>| {
            accepted.lock().unwrap().push(Arc::clone(&conn));
            let node = node.clone();
            let serve = Arc::clone(&serve);
            tokio::spawn(async move {
                if let Ok(mux) = node.protomux(&conn).await {
                    serve(node, mux, conn);
                }
            });
        })
    };
    let server = node.create_server(handler).await.expect("server");
    let key_pair = key(seed);
    server.listen(&key_pair).await.expect("listen");
    for topic in GUARD_TOPICS.iter() {
        node.announce(*topic, &key_pair).await.expect("announce");
    }
    (key_pair.public_key, accepted, server)
}

/// A `/v2` guard that answers `hello` with `status`, and closes the channel `close_after` later.
fn hello_guard(
    status: u64,
    close_after: Option<Duration>,
) -> impl Fn(fake::FakeDht, Mux, Arc<dyn Connection>) {
    move |_node: fake::FakeDht, mux: Mux, conn: Arc<dyn Connection>| {
        let handlers = ControlHandlers {
            handled: 1 << op::HELLO,
            on_request: Some(Arc::new(move |_, _, control: Control| {
                if let Some(after) = close_after {
                    tokio::spawn(async move {
                        tokio::time::sleep(after).await;
                        control.close();
                    });
                }
                Box::pin(async move { Ok(GuardAck { status }.into()) })
            })),
            ..ControlHandlers::default()
        };
        let serving = serve_channel(&mux, &GUARD_SPEC, handlers);
        mux.ready();
        tokio::spawn(async move {
            conn.closed().await;
            drop(serving);
        });
    }
}

/// Cutover: guards that refuse the `/v2` channel, refuse the endpoint, or close an accepted
/// channel later are not usable. The client closes its own connection to each, reports
/// UNAVAILABLE, and never dials the destination. Fails on any dial to a key that is not one of
