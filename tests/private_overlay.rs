/// Channel state: what `hello` granted and what the session holds (a route, a rendezvous slot,
/// a circuit it is the endpoint of) end with the channel, even though the connection stays. A
/// new channel on it starts with no role and registers after a fresh `hello`; the connection's
/// DHT budget is not reset by reopening. (A circuit granted after the close: see
/// `a_circuit_granted_after_its_channel_closed_is_refused`.)
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn a_closed_channel_releases_its_role_and_routes() {
    let net = FakeNet::new();
    let guard = create_private_guard(net.node().as_dht(), guard_options(50))
        .await
        .expect("guard");
    let first = endpoint(&net, guard.public_key(), 51, open_gate(), 1).await;
    let token = [0x31; 32];
    assert_eq!(ask(&first.rpc, op::REGISTER, register(token)).await, ack(1));
    let slot = rv_register([0x32; 32], [3; 16], &[4u8; 32]);
    assert_eq!(ask(&first.rpc, op::RV_REGISTER, slot).await, ack(1));
    let (hop, hop_rpc) = hop_session(&net, guard.public_key(), 49).await;
    let hop_raw = raw_stream(&hop).await;
    let open = GuardOpen {
        route_token: token,
        udx_id: u64::from(hop_raw.id()),
    };
    let Body::GuardReady(ready) = ask(&hop_rpc, op::HOP_OPEN, open).await else {
        panic!("not a ready")
    };
    assert_eq!(ready.status, 1);
    let stats = guard.stats();
    assert_eq!(
        (
            stats.registered_routes,
            stats.rendezvous_topics,
            stats.active_circuits
        ),
        (1, 1, 1)
    );

    // Spend the connection's whole DHT budget: one put, then reads of its record.
    let writer = key(48);
    let value = vec![1u8; 10];
    let put = GuardPutMutable {
        public_key: writer.public_key,
        seq: 1,
        signature: sign_dht_mutable(1, &value, &writer),
        value: value.into(),
    };
    assert_eq!(ask(&first.rpc, op::PUT_MUTABLE, put).await, ack(1));
    let read = GuardKey {
        key: writer.public_key,
    };
    let found = |answer: Body| {
        matches!(
            answer,
            Body::GuardGetResult(GuardGetResult { record: Some(_) })
        )
    };
    for _ in 1..peartube_native::private_overlay::MAX_DHT_OPS_PER_10S {
        assert!(found(ask(&first.rpc, op::GET_MUTABLE, read.clone()).await));
    }

    let second = close_channel_only(&first.client, &first.rpc).await;
    eventually("the session's holdings released", WAIT, || {
        let stats = guard.stats();
        (
            stats.registered_routes,
            stats.rendezvous_topics,
            stats.active_circuits,
        ) == (0, 0, 0)
    })
    .await;
    tokio::time::timeout(WAIT, hop_raw.closed())
        .await
        .expect("the circuit's streams are destroyed");
    assert!(!first.client.conn.is_closed());
    assert_eq!(ask(&second, op::REGISTER, register(token)).await, ack(0));
    assert_eq!(hello(&second, "endpoint").await, ack(1));
    assert_eq!(ask(&second, op::REGISTER, register(token)).await, ack(1));
    assert!(
        !found(ask(&second, op::GET_MUTABLE, read).await),
        "reopening the channel reset the connection's DHT budget"
    );
}

