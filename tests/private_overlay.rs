/// One source request each way over the rendezvousing stream.
async fn exchange(a: &mut NoiseConnection, b: &mut NoiseConnection) -> bool {
    let attempt = async {
        a.stream.write_all(b"source-request:hello").await.ok()?;
        b.stream.write_all(b"source-request:world").await.ok()?;
        let mut from_b = [0u8; 20];
        let mut from_a = [0u8; 20];
        a.stream.read_exact(&mut from_b).await.ok()?;
        b.stream.read_exact(&mut from_a).await.ok()?;
        (from_b == *b"source-request:world" && from_a == *b"source-request:hello").then_some(())
    };
    tokio::time::timeout(Duration::from_secs(6), attempt)
        .await
        .ok()
        .flatten()
        .is_some()
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn guards_and_swarms_rendezvous_and_exchange_bytes() {
    let net = FakeNet::new();
    let _guard_a = create_private_guard(net.node().as_dht(), guard_options(1))
        .await
        .expect("guard a");
    let _guard_b = create_private_guard(net.node().as_dht(), guard_options(2))
        .await
        .expect("guard b");

    let (tx_a, mut rx_a) = mpsc::unbounded_channel();
    let (tx_b, mut rx_b) = mpsc::unbounded_channel();
    let swarm_a = create_private_swarm(
        net.node().as_dht(),
        SwarmOptions {
            key_pair: Some(key(3)),
            allow_loopback: Some(true),
            on_connection: Some(Arc::new(move |connection: NoiseConnection| {
                let _ = tx_a.send(connection);
            })),
            ..SwarmOptions::default()
        },
    );
    let swarm_b = create_private_swarm(
        net.node().as_dht(),
        SwarmOptions {
            key_pair: Some(key(4)),
            allow_loopback: Some(true),
            on_connection: Some(Arc::new(move |connection: NoiseConnection| {
                let _ = tx_b.send(connection);
            })),
            ..SwarmOptions::default()
        },
    );

    let source_a = swarm_a.join_source("source", &SOURCE_KEY);
    let source_b = swarm_b.join_source("source", &SOURCE_KEY);
    assert_eq!(source_b.topic, source_a.topic);
    assert_eq!(source_a.topic, rv_topic(&SOURCE_KEY, &rv_epoch(now_ms())));
    assert!(swarm_a.status(source_a.topic).is_some());
    assert_eq!(swarm_a.topics().len(), 1);
    assert!(source_a.is_client);
    assert!(!source_a.is_server);

    eventually("both swarms ready", Duration::from_secs(15), || {
        let a = swarm_a.private_routing().status();
        let b = swarm_b.private_routing().status();
        matches!(a, RoutingState::Ready) && matches!(b, RoutingState::Ready)
    })
    .await;

    let report = swarm_a.private_routing().exposure_report();
    assert_eq!(report.hops, 2);
    assert_eq!(report.direct_destination_sends, 0);
    assert_eq!(report.guards, 2);

    eventually(
        "a connection on both sides",
        Duration::from_secs(20),
        || swarm_a.connection_count() == 1 && swarm_b.connection_count() == 1,
    )
    .await;

    let mut connection_a = tokio::time::timeout(Duration::from_secs(5), rx_a.recv())
        .await
        .expect("connection a")
        .expect("connection a channel");
    let mut connection_b = tokio::time::timeout(Duration::from_secs(5), rx_b.recv())
        .await
        .expect("connection b")
        .expect("connection b channel");
    assert_eq!(connection_a.remote_public_key, key(4).public_key);
    assert_eq!(connection_b.remote_public_key, key(3).public_key);

    // Simultaneous dials can leave each side holding a different half of the pair; the swarm
    // re-dials on its next poll, exactly like the app. Retry until one pair carries both ways.
    let mut exchanged = false;
    for _ in 0..5 {
        if exchange(&mut connection_a, &mut connection_b).await {
            exchanged = true;
            break;
        }
        connection_a = tokio::time::timeout(Duration::from_secs(15), rx_a.recv())
            .await
            .expect("a redial")
            .expect("a redial channel");
        connection_b = tokio::time::timeout(Duration::from_secs(15), rx_b.recv())
            .await
            .expect("b redial")
            .expect("b redial channel");
    }
    assert!(exchanged, "no working circuit carried bytes both ways");
    assert_ne!(connection_a.is_initiator, connection_b.is_initiator);

    // One spliced path is one circuit record in the guard that dialled it and one in the guard
    // that hopped it. A simultaneous dial on both sides makes two; the duplicate-connection rule
    // closes one, and each guard drops its circuit when the raw stream goes away.
    eventually(
        "the duplicate circuit to be torn down",
        Duration::from_secs(5),
        || _guard_a.stats().active_circuits == 1 && _guard_b.stats().active_circuits == 1,
    )
    .await;
    let stats_a = _guard_a.stats();
    let stats_b = _guard_b.stats();
    assert!(stats_a.registered_routes + stats_b.registered_routes >= 2);
    assert!(stats_a.rv_register_count + stats_b.rv_register_count >= 2);

    source_a.refresh().await;
    swarm_a.join_peer(key(4).public_key);
    swarm_a.leave_peer(key(4).public_key);
    swarm_a.leave_source("source").await;
    assert_eq!(swarm_a.topics().len(), 0);
    swarm_a.suspend().await;
    assert_eq!(swarm_a.private_routing().status(), RoutingState::Suspended);
    swarm_a.resume().await;
    assert_ne!(swarm_a.private_routing().status(), RoutingState::Suspended);
    swarm_a.clear().await;
    swarm_a.destroy().await;
    assert_eq!(swarm_a.private_routing().status(), RoutingState::Destroyed);
}

